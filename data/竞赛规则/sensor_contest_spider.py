    def extract_content(self, soup):
        """提取页面主要内容"""
        # 尝试多种常见的内容容器
        selectors = [
            'div.content', 'div#content', 'div.main', 'div.container',
            'article', 'section', '.detail', '.article-content'
        ]
        
        for selector in selectors:
            content = soup.select_one(selector)
            if content:
                return self.clean_text(content.get_text())
        
        # 如果找不到特定容器，提取body中的文本
        body = soup.find('body')
        if body:
            return self.clean_text(body.get_text())
        return ""

    def clean_text(self, text):
        """清理文本"""
        # 移除多余空白
        text = re.sub(r'\n\s*\n', '\n\n', text)
        text = re.sub(r'[ \t]+', ' ', text)
        # 移除特殊字符
        text = text.replace('\xa0', ' ').replace('\u3000', ' ')
        return text.strip()

    def categorize_ican_content(self, text):
        """将iCAN大赛内容分类存储"""
        # 参赛对象
        if '参赛对象' in text or '参赛队伍' in text:
            self.data["参赛要求"]["参赛对象"] = self.extract_section(text, ['参赛对象', '参赛队伍', '参赛人员'])
        
        # 评审标准
